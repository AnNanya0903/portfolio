"""KYC portal: the customer master.

Each customer has one customer code, which is the identity everything else maps to (enquiries,
quotations, emails). Contacts are grouped by team so automatic emails reach the right people:
payment reminders to accounts, drawings to technical, escalations to top management.
"""
from typing import List

from django.conf import settings
from django.db import models, transaction
from django.db.models.signals import post_save
from django.dispatch import receiver
from django.utils import timezone
from zoneinfo import ZoneInfo

from docscanner.storage import document_scan_storage

User = settings.AUTH_USER_MODEL

CUSTOMER_CODE_PREFIX = "AVG"
CUSTOMER_CODE_FIRST_NUMBER = 1001
# The year in the code is the year in India, so codes switch over at India New Year.
CUSTOMER_CODE_TIMEZONE = ZoneInfo("Asia/Kolkata")


def customer_code_text(year: int, number: int) -> str:
    """AVG-YY-NNNN, e.g. AVG-26-1001 (no leading zeros in the running number; YY is the last two digits)."""
    return f"{CUSTOMER_CODE_PREFIX}-{year % 100:02d}-{number}"


class CustomerCodeCounter(models.Model):
    """The last running number used for customer codes in one year. Changed only under a row lock
    (see `next_customer_code`), so two saves at the same time never get the same number.
    Numbers are never reused, even when a customer is deleted."""

    year = models.PositiveSmallIntegerField(unique=True)
    last_number = models.PositiveIntegerField(default=CUSTOMER_CODE_FIRST_NUMBER - 1)

    class Meta:
        db_table = "kyc_customer_code_counter"

    def __str__(self) -> str:
        return f"{self.year}: last {self.last_number}"


def next_customer_code(year: int) -> str:
    """The next customer code for a year. Must run inside a transaction: the counter row stays locked
    until that transaction commits, so no other save can take the same number."""
    if not transaction.get_connection().in_atomic_block:
        raise RuntimeError("next_customer_code must run inside a transaction.atomic() block.")
    CustomerCodeCounter.objects.get_or_create(year=year)
    counter = CustomerCodeCounter.objects.select_for_update().get(year=year)
    counter.last_number += 1
    counter.save(update_fields=["last_number"])
    return customer_code_text(year, counter.last_number)


class Customer(models.Model):
    KYC_DRAFT = "draft"
    KYC_SENT = "sent"
    KYC_VERIFIED = "verified"
    KYC_CHANGES = "changes"
    KYC_REJECTED = "rejected"
    KYC_STATUS_CHOICES = (
        (KYC_DRAFT, "Not verified"),
        (KYC_SENT, "Sent to customer"),
        (KYC_VERIFIED, "Verified by customer"),
        (KYC_CHANGES, "Customer asked for changes"),
        (KYC_REJECTED, "Rejected by customer"),
    )
    TRANSPORTER_CHOICES = [
        ('ARC', 'ARC'),
        ('VRL', 'VRL'),
        ('OTHER', 'Other'),
        ]
    
    DELIVERY_CHOICES = [
        ('DOOR', 'Door Delivery'),
        ('GODOWN', 'Go-Down Delivery'),
    ]

    # Stored in capitals without spaces, so "av-001" and "AV-001" are the same customer.
    code = models.CharField(
        "Customer code", max_length=32, unique=True,
        error_messages={"unique": "Another customer already has this customer code."},
    )
    # Generated by the system when the customer is first saved (AVG-YY-NNNN). Never typed, never changed.
    customer_code = models.CharField(
        "Customer code", max_length=20, unique=True, null=True, blank=True, editable=False,
        help_text="Generated automatically (AVG-YY-NNNN) when the customer is created.",
    )
    name = models.CharField("Company name", max_length=255)
    address = models.TextField(blank=True, default="")
    city = models.CharField(max_length=120, blank=True, default="")
    state = models.CharField(max_length=120, blank=True, default="")
    pincode = models.CharField("PIN / postal code", max_length=20, blank=True, default="")
    country = models.CharField(max_length=120, blank=True, default="India")

# Add these inside your existing KYC model

    transportation = models.CharField( max_length=150, blank=True, null=True ) 
    preferred_transporter = models.CharField( max_length=100, choices=TRANSPORTER_CHOICES, default='ARC', blank=True) 
    other_transporter = models.CharField( max_length=100, blank=True, null=True)
    delivery_type = models.CharField( max_length=20, choices=DELIVERY_CHOICES, blank=True, null=True)
    msme_applicable = models.BooleanField(default=False)
    udyam_aadhar_no = models.CharField(max_length=50, blank=True, null=True )
    gstin = models.CharField("GSTIN", max_length=15, blank=True, default="")
    pan = models.CharField("PAN", max_length=10, blank=True, default="")
    phone = models.CharField("Company phone", max_length=40, blank=True, default="")
    website = models.CharField(max_length=255, blank=True, default="")
    notes = models.TextField(blank=True, default="")
    kyc_status = models.CharField(max_length=10, choices=KYC_STATUS_CHOICES, default=KYC_DRAFT)
    # The teams that handle this customer: all active departments unless someone unticks some.
    # Every department can still see every customer.
    departments = models.ManyToManyField(
        "Department", verbose_name="Team", related_name="customers", db_table="kyc_customer_departments")

    created_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    updated_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "kyc_customer"
        ordering = ["name", "code"]

    def save(self, *args, **kwargs):
        if self._state.adding and not self.customer_code:
            # The code and the row are saved in one transaction, so a failed save uses no number.
            with transaction.atomic():
                self.customer_code = next_customer_code(timezone.now().astimezone(CUSTOMER_CODE_TIMEZONE).year)
                super().save(*args, **kwargs)
            return
        super().save(*args, **kwargs)

    def __str__(self) -> str:
        return f"{self.code} - {self.name}"


