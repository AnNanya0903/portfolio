class CustomerContact(models.Model):
    CATEGORY_SALES = "sales_marketing"
    CATEGORY_TECHNICAL = "technical"
    CATEGORY_ACCOUNTS = "accounts"
    CATEGORY_MANAGEMENT = "top_management"
    CATEGORY_QUALITY = "quality"
    CATEGORY_STORES = "stores_logistics"
    CATEGORY_CHOICES = (
        (CATEGORY_SALES, "Sales and marketing"),
        (CATEGORY_TECHNICAL, "Technical / design"),
        (CATEGORY_ACCOUNTS, "Accounts"),
        (CATEGORY_MANAGEMENT, "Top management"),
        (CATEGORY_QUALITY, "Quality"),
        (CATEGORY_STORES, "Stores / logistics"),
    )

    customer = models.ForeignKey(Customer, on_delete=models.CASCADE, related_name="contacts")
    category = models.CharField("Team", max_length=20, choices=CATEGORY_CHOICES)
    name = models.CharField(max_length=200)
    designation = models.CharField(max_length=200, blank=True, default="")
    email = models.CharField(max_length=254, blank=True, default="")
    phone = models.CharField(max_length=40, blank=True, default="")  # mobile number (10 digits in the form)
    alternate_phone = models.CharField("Alternate number", max_length=40, blank=True, default="")
    # The primary contact is the person enquiry and quotation emails go to. One per customer (see save()).
    is_purchaser = models.BooleanField("Primary contact", default=False)
    notes = models.CharField("Remarks", max_length=500, blank=True, default="")

    def email_addresses(self) -> List[str]:
        """The individual addresses stored in this contact's (comma-separated) email field."""
        return [part.strip() for part in (self.email or "").split(",") if part.strip()]

    @property
    def email_address(self) -> str:
        """First address, for places that need a single recipient (enquiry To, search)."""
        addresses = self.email_addresses()
        return addresses[0] if addresses else ""

    created_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    updated_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        db_table = "kyc_customer_contact"
        ordering = ["-is_purchaser", "name"]

    def save(self, *args, **kwargs):
        # Only one primary contact per customer: making this one primary makes the others not primary.
        with transaction.atomic():
            super().save(*args, **kwargs)
            if self.is_purchaser:
                CustomerContact.objects.filter(
                    customer_id=self.customer_id, is_purchaser=True).exclude(pk=self.pk).update(is_purchaser=False)

    def __str__(self) -> str:
        return f"{self.customer.code}:{self.category}:{self.name}"


class KycDocument(models.Model):
    """An existing KYC form (photo, PDF or pasted text) that a customer's details were read from.

    Uploaded first, read automatically, then checked by a person. `customer` is empty until that
    person saves the customer.
    """

    customer = models.ForeignKey(Customer, on_delete=models.CASCADE, null=True, blank=True, related_name="documents")
    file = models.FileField(upload_to="kyc/%Y/%m/", storage=document_scan_storage, blank=True)
    original_name = models.CharField(max_length=255, blank=True, default="")
    content_type = models.CharField(max_length=120, blank=True, default="")
    size_bytes = models.BigIntegerField(default=0)
    pasted_text = models.TextField(blank=True, default="")
    # {"customer": {...}, "contacts": [{...}]} as read from the document; empty when it could not be read.
    extracted_data = models.JSONField(default=dict, blank=True)
    error_message = models.CharField(max_length=500, blank=True, default="")
    uploaded_by = models.ForeignKey(User, on_delete=models.SET_NULL, null=True, blank=True, related_name="+")
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = "kyc_document"
        ordering = ["-created_at"]

    def __str__(self) -> str:
        return f"KycDocument:{self.pk}:{self.original_name or 'pasted text'}"

    @property
    def is_image(self) -> bool:
        return self.content_type.startswith("image/")


